"""Creative OS v2 — Golden Tests (M4).

Regression guard: the QA engine must keep PASSING known-good delivered work
and keep FAILING known-bad synthetic cases. Run after any engine/config change.
"""
import os, sys, glob, json
from PIL import Image, ImageDraw

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WS = os.path.dirname(ROOT)
sys.path.insert(0, os.path.join(ROOT, "lib"))
import qa_engine as Q
import prompt_compiler as PC

# Two fixture tiers:
# - PRIVATE: the maintainer's delivered production artwork (not tracked in the
#   public repo — client/brand work). Checked against the real brand hexes.
# - SYNTHETIC: committed fixtures under tests/fixtures/synthetic/, generated by
#   tests/make_synthetic_goldens.py from the PUBLIC example config, so every
#   clone runs the full golden shape deterministically.
PRIVATE_HEXES = ["#FF5A00", "#F5EFE6", "#1A1A1A"]
_ex = json.load(open(os.path.join(ROOT, "config", "brand.config.example.json")))
SYN_HEXES = [_ex["colors"]["primary"], _ex["colors"]["background"], _ex["colors"]["text"]]
FIX = os.path.join(ROOT, "tests", "fixtures", "synthetic")
SYN_BOX = (900, 40, 1040, 104)       # must match make_synthetic_goldens.py
SYN_TEXT_BOX = (920, 56, 1020, 88)
results = []


def check(name, ok, detail=""):
    results.append((name, ok, detail))
    print(("PASS " if ok else "FAIL ") + name + ("  " + str(detail) if detail and not ok else ""))


def skip(name, why):
    print("SKIP " + name + "  (" + why + ")")


# 1. Known-good finals must pass numeric suite.
#    Golden fixtures are the maintainer's privately delivered artwork and are
#    NOT tracked in the public repo — skip (don't fail) when they are absent.
goldens = sorted(glob.glob(os.path.join(WS, "facebook/week1/f*-post.png")))
if goldens:
    for p in goldens:
        img = Image.open(p)
        r = Q.run_numeric_suite(img, {"expected_size": (1080, 1350), "brand_hexes": PRIVATE_HEXES})
        check("golden-good " + os.path.basename(p), all(v["status"] == "pass" for v in r.values()), r)
else:
    skip("golden-good private finals", "maintainer's private delivered work, not tracked in the public repo")

# 1b. Synthetic known-good finals — committed to the repo, must ALWAYS run.
syn = sorted(glob.glob(os.path.join(FIX, "good-post-*.png")))
if syn:
    for p in syn:
        img = Image.open(p)
        r = Q.run_numeric_suite(img, {"expected_size": (1080, 1350), "brand_hexes": SYN_HEXES})
        check("golden-good synthetic " + os.path.basename(p), all(v["status"] == "pass" for v in r.values()), r)
else:
    check("synthetic post fixtures present", False,
          "missing tests/fixtures/synthetic/ — run tests/make_synthetic_goldens.py and commit the output")

# 2. Known-good series must hold QA26/27 (exclude _overview, exclude final slide)
seq = sorted(glob.glob(os.path.join(WS, "facebook/week1/seq-f2/f2-slide-*.png")))[:-1]
if len(seq) >= 2:
    slides = [Image.open(p) for p in seq]
    ok, d = Q.check_series_alignment(slides, (900, 30, 1050, 98), polarity="dark")
    check("golden-good seq-f2 QA26", ok, d)
    ok, d = Q.check_scale_lock(slides, (905, 40, 1045, 90), polarity="light")
    check("golden-good seq-f2 QA27", ok, d)
else:
    skip("golden-good private seq-f2 QA26/QA27", "maintainer's private delivered work, not tracked in the public repo")

# 2b. Synthetic known-good series — committed to the repo, must ALWAYS run.
sseq = sorted(glob.glob(os.path.join(FIX, "seq", "slide-*.png")))
if len(sseq) >= 2:
    sslides = [Image.open(p) for p in sseq]
    ok, d = Q.check_series_alignment(sslides, SYN_BOX, polarity="dark")
    check("golden-good synthetic seq QA26", ok, d)
    ok, d = Q.check_scale_lock(sslides, SYN_TEXT_BOX, polarity="light")
    check("golden-good synthetic seq QA27", ok, d)
else:
    check("synthetic series fixtures present", False,
          "missing tests/fixtures/synthetic/seq/ — run tests/make_synthetic_goldens.py and commit the output")

# 3. Synthetic BAD cases must FAIL
bad = Image.new("RGB", (1080, 1350), (196, 196, 196))  # off-brand grey (t8 v1 drift lesson)
r = Q.run_numeric_suite(bad, {"expected_size": (1080, 1350), "brand_hexes": SYN_HEXES})
check("golden-bad off-brand bg detected", r["QA03a"]["status"] == "fail", r["QA03a"])

wrong = Image.new("RGB", (1080, 1080), (245, 239, 230))
r = Q.run_numeric_suite(wrong, {"expected_size": (1080, 1350), "brand_hexes": SYN_HEXES})
check("golden-bad wrong canvas detected", r["QA01"]["status"] == "fail")

drift = [Image.new("RGB", (400, 200), (245, 239, 230)) for _ in range(3)]
for i, s in enumerate(drift):
    ImageDraw.Draw(s).rectangle([50 + i * 6, 50, 150 + i * 6, 120], fill=(26, 26, 26))  # 6px/slide drift
ok, _ = Q.check_series_alignment(drift, (0, 0, 400, 200), polarity="dark")
check("golden-bad series drift detected", not ok)

# 4. Prompt compiler contracts
reg = PC.load_registry()
try:
    PC.get_entry(reg, "DNA_16")
    check("tombstone hard-block", False)
except ValueError:
    check("tombstone hard-block", True)

entry = PC.get_entry(reg, "HOB_01")
# Same fallback as the orchestrator: real sample config is private (gitignored);
# public clones fall back to the fictional example config.
_cfg = os.path.join(ROOT, "config", "brand.config.sample.json")
if not os.path.exists(_cfg):
    _cfg = os.path.join(ROOT, "config", "brand.config.example.json")
brand = json.load(open(_cfg))
c = PC.compile_prompt({"topic": "cold email deliverability", "hero_description": "three hanging envelopes, one glowing orange",
                       "headline": "ONE EMAIL LANDS.", "format": "feed_45"}, brand, entry)
check("compiler: no pixel numbers leak", "px" not in c["prompt"] and "140" not in c["prompt"])
check("compiler: anti-artifact clause", "No guide lines" in c["prompt"])
check("compiler: anti-dilution clause", "Do not simplify" in c["prompt"])
_hx = brand["colors"]
check("compiler: exact hexes present", _hx["primary"] in c["prompt"] and _hx["background"] in c["prompt"])
check("compiler: reference attached", len(c["reference_images"]) >= 2)

fails = [n for n, ok, _ in results if not ok]
print(f"\n{len(results) - len(fails)}/{len(results)} golden tests passed" + (f" — FAILURES: {fails}" if fails else ""))
sys.exit(1 if fails else 0)
